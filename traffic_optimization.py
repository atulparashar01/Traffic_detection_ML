from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier
from sklearn.metrics import classification_report, confusion_matrix, accuracy_score
import matplotlib.pyplot as plt
import seaborn as sns

# Select features (bounding box coordinates) and target (class_id)
X = df_traffic[['xmin', 'xmax', 'ymin', 'ymax']]
y = df_traffic['class_id']

# Train-test split
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

models = {
    'Random Forest': RandomForestClassifier(n_estimators=100, random_state=42),
    'KNN': KNeighborsClassifier()
}

results = {}
for name, model in models.items():
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    results[name] = accuracy

    # Print classification report and confusion matrix for each model
    print(f"Classification Report for {name}:\n", classification_report(y_test, y_pred))
    print(f"Confusion Matrix for {name}:\n", confusion_matrix(y_test, y_pred))

    # Visualization: Confusion Matrix for each model
    plt.figure(figsize=(6, 4))
    sns.heatmap(confusion_matrix(y_test, y_pred), annot=True, fmt="d", cmap="Blues", cbar=False)
    plt.xlabel("Predicted Label")
    plt.ylabel("True Label")
    plt.title(f"Confusion Matrix for {name}")
    plt.show()

# Plot Comparison of Accuracy
plt.figure(figsize=(8, 6))


colors = ['teal', 'darkorange']

bars = plt.bar(results.keys(), results.values(), color=colors, edgecolor='black')
plt.title("Accuracy Comparison Across Models", fontsize=14, weight='bold')
plt.xlabel("Model", fontsize=12)
plt.ylabel("Accuracy Score", fontsize=12)
plt.grid(axis='y', linestyle='--', alpha=0.5)

for bar in bars:
    height = bar.get_height()
    plt.annotate(f'{height:.2f}',
                 xy=(bar.get_x() + bar.get_width() / 2, height),
                 xytext=(0, 5),  # 5 points vertical offset
                 textcoords="offset points",
                 ha='center', va='bottom', fontsize=10, color='black')

plt.tight_layout()
plt.show()

# Feature Importance for Random Forest
feature_importances = pd.Series(models['Random Forest'].feature_importances_, index=X.columns)
plt.figure(figsize=(8, 6))
feature_importances.sort_values().plot(kind='barh', color='darkorange', edgecolor='black')
plt.title("Feature Importance in Random Forest Classifier", fontsize=14, weight='bold')
plt.xlabel("Importance Score", fontsize=12)
plt.ylabel("Features", fontsize=12)
plt.grid(axis='x', linestyle='--', alpha=0.5)
plt.tight_layout()
plt.show()

