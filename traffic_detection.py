#Import Libraries
from ultralytics import YOLO
from IPython.display import Image, display
from pathlib import Path
import shutil

#Define the path to your image folder
image_folder = "/content/drive/MyDrive/Colab Notebooks/dataset/images"

#Load YOLOv8 Model
model = YOLO("yolov8n.pt")

#Run Object Detection
results = model.predict(
    source=image_folder,
    save=True,
    project="runs/detect",
    name="traffic_detect_drive",
    conf=0.3
)

#Display First Few Detected Images
output_path = Path("runs/detect/traffic_detect_drive")
image_files = list(output_path.glob("*.jpg")) + list(output_path.glob("*.png"))

print(f"\n Displaying {min(5, len(image_files))} results from {output_path}:")
for image_path in image_files[:5]:
    display(Image(filename=str(image_path)))

import matplotlib.pyplot as plt

num_images = min(4, len(results))

plt.figure(figsize=(16, 10))

for i in range(num_images):
    img = results[i].plot()
    plt.subplot(1, num_images, i + 1)
    plt.imshow(img)
    plt.axis("off")
    plt.title(f"Image {i+1}")

plt.suptitle("YOLOv8 Detections", fontsize=16)
plt.tight_layout()
plt.show()

